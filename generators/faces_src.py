#!/usr/bin/env python3
"""Lumina face design: the single source for every Emacs face.

Writes spec/faces.json, which generators/lumina_gen.py resolves per flavor.
Edit this file, then `make build`.

Color refs: a palette slot (bg, fg, base0..base8, surface, overlay, halo,
halo2, region, glow, dim, red .. magenta, <accent>-bg, diff-*-bg, ...),
a helper (comments, strings, keywords, functions, type, builtin, constants,
variables, numbers, operators, ...) or a schema slot (schema.lead,
schema.outline[n], schema.rainbow[n], schema.orderless[n], schema.escape,
schema.property, schema.function_call, schema.preprocessor, ...).

Design rules (Lumina 2):
  one lamp   schema.lead = cursor, prompts, keys, selected item, definitions
  grounds    surface = inline panels, overlay = popups, bg-alt = chrome,
             halo = current line, halo2 = selected candidate, glow = flash,
             <accent>-bg = tinted ground for states (added, error, habit ...)
  weight     semi-bold only; bold is reserved for the `bold' face itself
  states     red error/removed, orange warning/modified, yellow changed,
             green success/added, teal remote/alt, cyan info/hint,
             blue link/local, violet date/special, magenta constant/other
"""
