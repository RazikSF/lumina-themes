def f(fg=None, bg=None, *, b=False, i=False, w=None, u=None, box=None, inh=None,
      h=None, ext=False, ov=None, strike=None, inv=False, sl=None):
    d = {}
    if fg is not None:
        d["fg"] = fg
    if bg is not None:
        d["bg"] = bg
    if w:
        d["weight"] = w
    elif b:
        d["bold"] = True
    if sl:
        d["slant"] = sl
    elif i:
        d["italic"] = True
    if u is not None:
        d["underline"] = u
    if box is not None:
        d["box"] = box
    if ov:
        d["overline"] = ov
    if strike is not None:
        d["strike-through"] = strike
    if inv:
        d["inverse"] = True
    if ext:
        d["extend"] = True
    if inh:
        d["inherit"] = inh
    if h:
        d["height"] = h
    return d


def wave(c):
    return {"color": c, "style": "wave"}


def line(c):
    return {"color": c, "style": "line"}


def box(c, w=1, style=None):
    d = {"width": w, "color": c}
    if style:
        d["style"] = style
    return d


def inh(name):
    return {"inherit": name}


